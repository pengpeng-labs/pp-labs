static unsigned char rsa_e[] = { 0x01, 0x00, 0x01 };

static br_rsa_public_key server_key = {
    (unsigned char *)rsa_n, sizeof(rsa_n), (unsigned char *)rsa_e, sizeof(rsa_e)
};

static br_x509_knownkey_context knownkey_ctx;

/* 设置 fixed knownkey 验证（跳过链验证，只校验服务器公钥匹配） */
void pp_tls_set_knownkey(br_ssl_client_context *sc)
{
    br_x509_knownkey_init_rsa(&knownkey_ctx, &server_key, 0x30); /* KEYX | SIGN */
    br_ssl_engine_set_x509(&sc->eng, &knownkey_ctx.vtable);
}

/* 引擎最近一次错误码（inline 包装，供 pp 侧读取） */
int pp_tls_last_error(br_ssl_client_context *sc)
{
    return br_ssl_engine_last_error(&sc->eng);
}
